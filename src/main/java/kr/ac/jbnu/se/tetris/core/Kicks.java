package kr.ac.jbnu.se.tetris.core;

/**
 * SRS 킥 테이블 (RULES 6.2). 값은 {dx, dy} 이고 <b>dy &gt; 0 이 아래쪽</b>이다.
 * 테트리스 위키의 표(위쪽이 +y)와 y 부호가 반대다.
 */
final class Kicks {

	/** [from][to 가 시계 방향이면 0, 반시계 방향이면 1][시도 번호] = {dx, dy} */
	private static final int[][][][] JLSTZ = {
			{ // 0 →
					{ { 0, 0 }, { -1, 0 }, { -1, -1 }, { 0, 2 }, { -1, 2 } },  // 0 → R
					{ { 0, 0 }, { 1, 0 }, { 1, -1 }, { 0, 2 }, { 1, 2 } } },   // 0 → L
			{ // R →
					{ { 0, 0 }, { 1, 0 }, { 1, 1 }, { 0, -2 }, { 1, -2 } },    // R → 2
					{ { 0, 0 }, { 1, 0 }, { 1, 1 }, { 0, -2 }, { 1, -2 } } },  // R → 0
			{ // 2 →
					{ { 0, 0 }, { 1, 0 }, { 1, -1 }, { 0, 2 }, { 1, 2 } },     // 2 → L
					{ { 0, 0 }, { -1, 0 }, { -1, -1 }, { 0, 2 }, { -1, 2 } } }, // 2 → R
			{ // L →
					{ { 0, 0 }, { -1, 0 }, { -1, 1 }, { 0, -2 }, { -1, -2 } },  // L → 0
					{ { 0, 0 }, { -1, 0 }, { -1, 1 }, { 0, -2 }, { -1, -2 } } } }; // L → 2

	private static final int[][][][] I = {
			{ // 0 →
					{ { 0, 0 }, { -2, 0 }, { 1, 0 }, { -2, 1 }, { 1, -2 } },   // 0 → R
					{ { 0, 0 }, { -1, 0 }, { 2, 0 }, { -1, -2 }, { 2, 1 } } }, // 0 → L
			{ // R →
					{ { 0, 0 }, { -1, 0 }, { 2, 0 }, { -1, -2 }, { 2, 1 } },   // R → 2
					{ { 0, 0 }, { 2, 0 }, { -1, 0 }, { 2, -1 }, { -1, 2 } } }, // R → 0
			{ // 2 →
					{ { 0, 0 }, { 2, 0 }, { -1, 0 }, { 2, -1 }, { -1, 2 } },   // 2 → L
					{ { 0, 0 }, { 1, 0 }, { -2, 0 }, { 1, 2 }, { -2, -1 } } }, // 2 → R
			{ // L →
					{ { 0, 0 }, { 1, 0 }, { -2, 0 }, { 1, 2 }, { -2, -1 } },   // L → 0
					{ { 0, 0 }, { -2, 0 }, { 1, 0 }, { -2, 1 }, { 1, -2 } } } }; // L → 2

	private static final int[][] NONE = { { 0, 0 } };

	private Kicks() {
	}

	static int[][] tests(PieceType type, int from, boolean clockwise) {
		int dir = clockwise ? 0 : 1;
		switch (type) {
		case O:
			return NONE;
		case I:
			return I[from][dir];
		default:
			return JLSTZ[from][dir];
		}
	}
}
